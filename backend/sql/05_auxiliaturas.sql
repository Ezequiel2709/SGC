-- ADVERTENCIAS:
--   * Reemplaza DOS tablas anteriores, SOLO SI AMBAS CONTINUAN VACIAS.
--   * No utilizar CASCADE. Dependencias ajenas abortaran la transaccion.
--   * No es una migracion repetible: ejecutar una sola vez en sgc_db.
--   * Los criterios 40/36/24 del formulario CPD se configuraran por convocatoria
