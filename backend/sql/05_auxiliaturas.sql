BEGIN;

-- Bloqueo preventivo: impide que otra sesion agregue filas durante el reemplazo.
LOCK TABLE public.postulaciones_auxiliatura, public.convocatorias_auxiliatura
  IN ACCESS EXCLUSIVE MODE;

DO $$
BEGIN
  IF to_regclass('public.convocatorias_auxiliatura') IS NULL
     OR to_regclass('public.postulaciones_auxiliatura') IS NULL THEN
    RAISE EXCEPTION 'Falta una tabla antigua. No se modifico la base de datos.';
  END IF;
  IF EXISTS (SELECT 1 FROM public.convocatorias_auxiliatura)
     OR EXISTS (SELECT 1 FROM public.postulaciones_auxiliatura) THEN
    RAISE EXCEPTION 'Hay datos en las tablas antiguas. Operacion cancelada.';
  END IF;
  IF to_regclass('public.materias') IS NULL
     OR to_regclass('public.estudiantes') IS NULL THEN
    RAISE EXCEPTION 'No existen las tablas compartidas materias y estudiantes.';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM pg_constraint fk
    WHERE fk.contype = 'f'
      AND fk.confrelid IN (
        'public.convocatorias_auxiliatura'::regclass,
        'public.postulaciones_auxiliatura'::regclass
      )
      AND fk.conrelid NOT IN (
        'public.convocatorias_auxiliatura'::regclass,
        'public.postulaciones_auxiliatura'::regclass
      )
  ) THEN
    RAISE EXCEPTION 'Existen dependencias externas nuevas. Operacion cancelada.';
  END IF;
END $$;

-- Postulaciones referencia convocatorias: respetar este orden.
DROP TABLE public.postulaciones_auxiliatura;
DROP TABLE public.convocatorias_auxiliatura;

-- 1. CONVOCATORIAS
CREATE TABLE public.convocatorias_auxiliatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  materia_id BIGINT NOT NULL REFERENCES public.materias(id) ON DELETE RESTRICT,
  gestion INTEGER NOT NULL CHECK (gestion BETWEEN 2000 AND 2100),
  semestre SMALLINT NOT NULL CHECK (semestre IN (1, 2)),
  titulo VARCHAR(200) NOT NULL CHECK (btrim(titulo) <> ''),
  descripcion TEXT,
  requisitos_generales TEXT,
  fecha_apertura DATE NOT NULL,
  fecha_cierre DATE NOT NULL,
  fecha_examen DATE,
  cupos INTEGER NOT NULL CHECK (cupos >= 1),
  estado VARCHAR(20) NOT NULL DEFAULT 'borrador'
    CHECK (estado IN ('borrador', 'publicada', 'cerrada', 'evaluacion', 'finalizada', 'anulada')),
  resultados_publicados BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_publicacion_resultados TIMESTAMPTZ,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_convocatoria_fechas CHECK (fecha_cierre >= fecha_apertura),
  CONSTRAINT ck_convocatoria_fecha_examen CHECK (
    fecha_examen IS NULL OR fecha_examen >= fecha_apertura
  ),
  CONSTRAINT ck_convocatoria_publicacion CHECK (
    (NOT resultados_publicados AND fecha_publicacion_resultados IS NULL)
    OR (resultados_publicados AND fecha_publicacion_resultados IS NOT NULL)
  ),
  UNIQUE (materia_id, gestion, semestre)
);

-- Requisitos configurables de cada convocatoria.
CREATE TABLE public.requisitos_convocatoria_auxiliatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  convocatoria_id BIGINT NOT NULL REFERENCES public.convocatorias_auxiliatura(id) ON DELETE RESTRICT,
  descripcion TEXT NOT NULL CHECK (btrim(descripcion) <> ''),
  obligatorio BOOLEAN NOT NULL DEFAULT TRUE,
  orden SMALLINT NOT NULL CHECK (orden > 0),
  UNIQUE (convocatoria_id, orden)
);

-- 2. POSTULACIONES
CREATE TABLE public.postulaciones_auxiliatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  convocatoria_id BIGINT NOT NULL REFERENCES public.convocatorias_auxiliatura(id) ON DELETE RESTRICT,
  estudiante_id BIGINT NOT NULL REFERENCES public.estudiantes(id) ON DELETE RESTRICT,
  fecha_postulacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  estado VARCHAR(22) NOT NULL DEFAULT 'registrada'
    CHECK (estado IN ('registrada', 'en_revision', 'habilitada',
                     'no_habilitada', 'evaluada', 'seleccionada',
                     'no_seleccionada', 'retirada')),
  observaciones TEXT,
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (convocatoria_id, estudiante_id)
);

-- Archivos privados: guardar SOLO ruta interna/controlada, no contrasenas
-- ni URL publica. La carga/descarga autenticada se implementa en backend.
CREATE TABLE public.documentos_postulacion_auxiliatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  postulacion_id BIGINT NOT NULL REFERENCES public.postulaciones_auxiliatura(id) ON DELETE RESTRICT,
  tipo_documento VARCHAR(60) NOT NULL CHECK (btrim(tipo_documento) <> ''),
  nombre_archivo VARCHAR(255) NOT NULL CHECK (btrim(nombre_archivo) <> ''),
  ruta_privada TEXT NOT NULL CHECK (btrim(ruta_privada) <> ''),
  estado VARCHAR(18) NOT NULL DEFAULT 'entregado'
    CHECK (estado IN ('entregado', 'observado', 'aprobado', 'rechazado')),
  observaciones TEXT,
  fecha_entrega TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 3. VERIFICACION DE CADA REQUISITO
CREATE TABLE public.verificaciones_requisitos_auxiliatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  postulacion_id BIGINT NOT NULL REFERENCES public.postulaciones_auxiliatura(id) ON DELETE RESTRICT,
  requisito_id BIGINT NOT NULL REFERENCES public.requisitos_convocatoria_auxiliatura(id) ON DELETE RESTRICT,
  cumple BOOLEAN, -- NULL: aun no revisado; TRUE/FALSE: revisado
  observaciones TEXT,
  fecha_revision TIMESTAMPTZ,
  UNIQUE (postulacion_id, requisito_id)
);

-- 4. EVALUACIONES: criterios editables por convocatoria, incluyendo los
--    criterios de CPD y examen. No se asume una escala universal.
CREATE TABLE public.criterios_evaluacion_auxiliatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  convocatoria_id BIGINT NOT NULL REFERENCES public.convocatorias_auxiliatura(id) ON DELETE RESTRICT,
  codigo VARCHAR(40) NOT NULL CHECK (btrim(codigo) <> ''),
  nombre VARCHAR(150) NOT NULL CHECK (btrim(nombre) <> ''),
  puntaje_maximo NUMERIC(7,2) NOT NULL CHECK (puntaje_maximo > 0),
  orden SMALLINT NOT NULL CHECK (orden > 0),
  UNIQUE (convocatoria_id, codigo),
  UNIQUE (convocatoria_id, orden)
);

CREATE TABLE public.evaluaciones_auxiliatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  postulacion_id BIGINT NOT NULL REFERENCES public.postulaciones_auxiliatura(id) ON DELETE RESTRICT,
  criterio_id BIGINT NOT NULL REFERENCES public.criterios_evaluacion_auxiliatura(id) ON DELETE RESTRICT,
  puntaje NUMERIC(7,2) NOT NULL CHECK (puntaje >= 0),
  observaciones TEXT,
  fecha_evaluacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (postulacion_id, criterio_id)
);

-- Identificacion de la comision por convocatoria. Las firmas se conservan
-- en el acta/documento adjunto; no se simulan firmas digitales.
CREATE TABLE public.evaluadores_auxiliatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  convocatoria_id BIGINT NOT NULL REFERENCES public.convocatorias_auxiliatura(id) ON DELETE RESTRICT,
  nombre_docente VARCHAR(180) NOT NULL CHECK (btrim(nombre_docente) <> ''),
  codigo_docente VARCHAR(50),
  tipo VARCHAR(12) NOT NULL CHECK (tipo IN ('titular', 'invitado')),
  orden SMALLINT NOT NULL CHECK (orden BETWEEN 1 AND 3),
  UNIQUE (convocatoria_id, orden)
);

-- 5. RESULTADOS: la decision NO es automatica. La directora registra
--    la decision VALIDADA y la publicacion se controla por convocatoria.
CREATE TABLE public.resultados_auxiliatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  postulacion_id BIGINT NOT NULL UNIQUE
    REFERENCES public.postulaciones_auxiliatura(id) ON DELETE RESTRICT,
  decision VARCHAR(17) NOT NULL
    CHECK (decision IN ('seleccionado', 'no_seleccionado')),
  observaciones TEXT,
  fecha_validacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Integridad: no se puede verificar/revisar un requisito de OTRA convocatoria.
CREATE FUNCTION public.sgc_aux_validar_requisito()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_conv_post BIGINT;
  v_conv_req BIGINT;
BEGIN
  SELECT convocatoria_id INTO v_conv_post
  FROM public.postulaciones_auxiliatura WHERE id = NEW.postulacion_id;
  SELECT convocatoria_id INTO v_conv_req
  FROM public.requisitos_convocatoria_auxiliatura WHERE id = NEW.requisito_id;
  IF v_conv_post IS DISTINCT FROM v_conv_req THEN
    RAISE EXCEPTION 'El requisito no pertenece a la convocatoria de la postulacion.';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_sgc_aux_validar_requisito
BEFORE INSERT OR UPDATE OF postulacion_id, requisito_id
ON public.verificaciones_requisitos_auxiliatura
FOR EACH ROW EXECUTE FUNCTION public.sgc_aux_validar_requisito();

-- Integridad: criterio de la MISMA convocatoria y puntaje no mayor al maximo.
CREATE FUNCTION public.sgc_aux_validar_evaluacion()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_conv_post BIGINT;
  v_conv_criterio BIGINT;
  v_maximo NUMERIC(7,2);
BEGIN
  SELECT convocatoria_id INTO v_conv_post
  FROM public.postulaciones_auxiliatura WHERE id = NEW.postulacion_id;
  SELECT convocatoria_id, puntaje_maximo INTO v_conv_criterio, v_maximo
  FROM public.criterios_evaluacion_auxiliatura WHERE id = NEW.criterio_id;
  IF v_conv_post IS DISTINCT FROM v_conv_criterio THEN
    RAISE EXCEPTION 'El criterio no corresponde a la convocatoria del postulante.';
  END IF;
  IF NEW.puntaje > v_maximo THEN
    RAISE EXCEPTION 'Puntaje % excede el maximo % del criterio.', NEW.puntaje, v_maximo;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_sgc_aux_validar_evaluacion
BEFORE INSERT OR UPDATE OF postulacion_id, criterio_id, puntaje
ON public.evaluaciones_auxiliatura
FOR EACH ROW EXECUTE FUNCTION public.sgc_aux_validar_evaluacion();

CREATE INDEX idx_aux_post_convocatoria ON public.postulaciones_auxiliatura(convocatoria_id);
CREATE INDEX idx_aux_post_estudiante ON public.postulaciones_auxiliatura(estudiante_id);
CREATE INDEX idx_aux_doc_postulacion ON public.documentos_postulacion_auxiliatura(postulacion_id);
CREATE INDEX idx_aux_ver_postulacion ON public.verificaciones_requisitos_auxiliatura(postulacion_id);
CREATE INDEX idx_aux_eval_postulacion ON public.evaluaciones_auxiliatura(postulacion_id);
CREATE INDEX idx_aux_eval_criterio ON public.evaluaciones_auxiliatura(criterio_id);
CREATE INDEX idx_aux_result_decision ON public.resultados_auxiliatura(decision);

-- Vista de notas: NULL mientras falte configurar o completar algun criterio.
-- No selecciona automaticamente al ganador; los cupos y empates deben
-- validarse en una transaccion del backend con decision de Direccion.
CREATE VIEW public.v_puntajes_auxiliatura AS
SELECT
    p.id AS postulacion_id,
    p.convocatoria_id,
    p.estudiante_id,
    COUNT(c.id)::INTEGER AS criterios_configurados,
    COUNT(e.puntaje)::INTEGER AS criterios_calificados,
    CASE
      WHEN COUNT(c.id) > 0 AND COUNT(e.puntaje) = COUNT(c.id)
      THEN COALESCE(SUM(e.puntaje), 0)::NUMERIC(9,2)
      ELSE NULL
    END AS puntaje_total
FROM public.postulaciones_auxiliatura p
JOIN public.convocatorias_auxiliatura v ON v.id = p.convocatoria_id
LEFT JOIN public.criterios_evaluacion_auxiliatura c ON c.convocatoria_id = v.id
LEFT JOIN public.evaluaciones_auxiliatura e
  ON e.postulacion_id = p.id AND e.criterio_id = c.id
GROUP BY p.id, p.convocatoria_id, p.estudiante_id;

CREATE VIEW public.v_resultados_auxiliatura AS
SELECT
  v.convocatoria_id,
  p.id AS postulacion_id,
  p.estudiante_id,
  p.estado AS estado_postulacion,
  v.puntaje_total,
  r.decision,
  r.observaciones,
  c.resultados_publicados,
  c.fecha_publicacion_resultados
FROM public.postulaciones_auxiliatura p
JOIN public.convocatorias_auxiliatura c ON c.id = p.convocatoria_id
LEFT JOIN public.v_puntajes_auxiliatura v ON v.postulacion_id = p.id
LEFT JOIN public.resultados_auxiliatura r ON r.postulacion_id = p.id;

COMMIT;

-- Comprobacion final (solo lectura; se ejecuta tras COMMIT).
SELECT table_name AS tabla
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN (
    'convocatorias_auxiliatura',
    'requisitos_convocatoria_auxiliatura',
    'postulaciones_auxiliatura',
    'documentos_postulacion_auxiliatura',
    'verificaciones_requisitos_auxiliatura',
    'criterios_evaluacion_auxiliatura',
    'evaluaciones_auxiliatura',
    'evaluadores_auxiliatura',
    'resultados_auxiliatura'
  )
ORDER BY table_name;
